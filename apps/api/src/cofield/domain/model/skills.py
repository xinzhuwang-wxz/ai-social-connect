#: 校园里根本不存在的专业，而跨专业那条软目标会因此永远算不出东西来。
#:
#: 它不是本事，放在这里是因为它和 `SKILLS` 一样是**封闭词表**：
#: 匹配读它（跨专业多样性），所以它必须来自一处。
