"""平台认识的本事。

## 为什么必须是闭集合

`needs` 直接喂给 SQL 的精确过滤（`skills && needs`）。词表外的值匹配
**零个人**——用户发一条再正常不过的需求（"缺个会剪辑的"），如果抽出来的是
`会剪辑` 而不是 `剪辑`，他会得到一句"凑不出队"，而校园里明明有两百个人会剪辑。

这个 bug 真的发生过：抽取器把修饰词一起卷进来，词表对不上，整条需求
静默地永远匹配不到人。静默是最坏的部分——没有报错，只是结果永远为空。

## 词表外的东西去哪了

**不丢。** 原话一直完整保留在 `raw_expression` 里，而语义召回读的就是它——
"想找个写朋克风格文案的"里的"朋克"从来就不在词表里，那一路本来就是
为它准备的。

结构化字段装得下的走 SQL，装不下的走向量。抽取器要做的是**认出哪些属于
前者**，而不是把所有东西都塞进前者。

## 一份词表，两处使用

合成人口按这份词表生成技能，抽取器按同一份词表归一。两处各写一份的话，
仿真里会出现现实中抽不出来的技能，而那种测试跑得再绿也证明不了什么。
"""

from __future__ import annotations

import re

#: 平台认识的本事。加一项要同时想清楚：抽取器认不认得出它的常见说法。
SKILLS: frozenset[str] = frozenset(
    {
        "写文案",
        "做PPT",
        "拍照",
        "翻译",
        "写脚本",
        "数据分析",
        "前端",
        "海报设计",
        "后端",
        "拍摄",
        "主持",
        "剪辑",
        "配乐",
        "调色",
        "三维建模",
        "动效",
    }
)

#: 用户不会照着词表说话。
#:
#: 这不是"同义词扩展"——每一条都是**实际会被说出来的说法**，
#: 加进来之前先问一句"真有人这么说吗"。凭空扩充只会让归一变得难以预测。
ALIASES: dict[str, str] = {
    "文案": "写文案",
    "撰稿": "写文案",
    "写稿": "写文案",
    "PPT": "做PPT",
    "ppt": "做PPT",
    "幻灯片": "做PPT",
    "摄影": "拍照",
    "摄像": "拍摄",
    "视频剪辑": "剪辑",
    "剪片": "剪辑",
    "剪视频": "剪辑",
    "后期": "剪辑",
    "英语": "翻译",
    "笔译": "翻译",
    "口译": "翻译",
    "脚本": "写脚本",
    "分镜": "写脚本",
    "数据": "数据分析",
    "统计": "数据分析",
    "前端开发": "前端",
    "网页": "前端",
    "后端开发": "后端",
    "服务端": "后端",
    "海报": "海报设计",
    "平面设计": "海报设计",
    "视觉": "海报设计",
    "主持人": "主持",
    "配音": "配乐",
    "音乐": "配乐",
    "调色师": "调色",
    "建模": "三维建模",
    "3D": "三维建模",
    "动画": "动效",
    "动态设计": "动效",
}

#: 说法前面常挂的修饰。"会剪辑"的意思和"剪辑"一样，多出来的字是噪音。
_MODIFIERS = re.compile(
    r"^(?:一?个|两个|三个|几个|某个|位|名|"
    r"会|懂|能|擅长|做|搞|干|负责|精通|熟悉|了解|有|要|找|需要|想)+"
)

#: 后面常挂的。
_TAIL = re.compile(r"(?:的人|的同学|的伙伴|的队友|的人选|的|人|同学)$")


def normalise(phrase: str) -> str | None:
    """把一句自然说法映射到词表里的一个词。映射不到就返回 `None`。

    **返回 `None` 不是失败**，是一个诚实的答复：这句话说的东西结构化字段
    装不下。调用方该做的是把它留给语义召回，并且让用户看到系统只认出了一部分。

    匹配分三步，越靠后越宽松：

    1. 剥掉修饰后精确命中词表
    2. 命中别名表
    3. **包含**——"会剪辑和调色"这种没被拆干净的短语里含着一个词表词

    第三步刻意放在最后：它最宽松，也最容易误伤（"不想做PPT"里含"做PPT"），
    所以只在前两步都不中时才用，而否定式已经在抽取那一层被专门处理过。
    """
    text = phrase.strip(" 　的和与、,，")
    if not text:
        return None

    stripped = _TAIL.sub("", _MODIFIERS.sub("", text)).strip()
    for candidate in (stripped, text):
        if candidate in SKILLS:
            return candidate
        if candidate in ALIASES:
            return ALIASES[candidate]

    # 长词优先：含"三维建模"的短语不该被"建模"抢先匹配掉。
    for skill in sorted(SKILLS, key=len, reverse=True):
        if skill in text:
            return skill
    for alias in sorted(ALIASES, key=len, reverse=True):
        if alias in text:
            return ALIASES[alias]
    return None


